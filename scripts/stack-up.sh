#!/usr/bin/env bash
# stack-up.sh — one-click FULL local stack in Docker: env files, image build,
# containers up, migrations + demo seed, health check.
#
# Everything (postgres, redis, rustfs, mailhog, adminer, redisinsight,
# javascript-executor, worker, realtime, builder) runs in containers on the
# inboxos network — nothing needs pnpm/node on the host besides docker.
#
# Usage:
#   ./scripts/stack-up.sh             # env → build (cached) → up → verify
#   ./scripts/stack-up.sh --build     # force rebuild of app images
#   ./scripts/stack-up.sh --logs      # same, then tail all service logs
#   ./scripts/stack-up.sh --down      # stop the whole stack (keeps volumes)
#   ./scripts/stack-up.sh --reset     # down -v + wipe .env.docker, then full up
#
# Demo login (seeded): demo@example.com / Demo@1234 → http://localhost:3123
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"

COMPOSE=(docker compose -f docker-compose.dev.yml -f docker-compose.override.yml)
BUILDER_PORT=3123
HEALTH_URL="http://localhost:${BUILDER_PORT}/api/health"

ENV_FILE=.env
ENV_DOCKER=.env.docker

log() { printf '\033[1;36m[stack-up]\033[0m %s\n' "$*"; }
die() { printf '\033[1;31m[stack-up] ERROR:\033[0m %s\n' "$*" >&2; exit 1; }

# ── env helpers ─────────────────────────────────────────────────────────────

# Read a KEY=value from .env (returns empty when unset).
env_get() { grep -E "^$1=" "$ENV_FILE" 2>/dev/null | tail -1 | cut -d= -f2- || true; }

# Replace or append KEY=value in a file.
env_set() { # env_set KEY VALUE FILE
  if grep -qE "^$1=" "$3" 2>/dev/null; then
    sed -i -E "s|^$1=.*|$1=$2|" "$3"
  else
    printf '%s=%s\n' "$1" "$2" >>"$3"
  fi
}

ensure_base_env() {
  if [[ ! -f "$ENV_FILE" ]]; then
    log "no .env — generating from .env.example with fresh secrets"
    cp .env.example "$ENV_FILE"
    env_set BETTER_AUTH_SECRET          "$(openssl rand -base64 32)" "$ENV_FILE"
    env_set ENCRYPTION_KEY              "$(openssl rand -hex 32)"    "$ENV_FILE"
    env_set JAVASCRIPT_EXECUTOR_TOKEN   "$(openssl rand -hex 32)"    "$ENV_FILE"
    env_set ZALO_PERSONAL_GATEWAY_TOKEN "$(openssl rand -hex 32)"    "$ENV_FILE"
    env_set ZALO_PERSONAL_WEBHOOK_SECRET "$(openssl rand -hex 16)"   "$ENV_FILE"
    env_set REALTIME_BROADCAST_SECRET   "$(openssl rand -hex 32)"    "$ENV_FILE"
  fi
}

# Container-side overrides: rewrite host endpoints to in-network service names.
# Idempotent — regenerated on every run; values follow .env credentials.
write_docker_env() {
  local pg_user pg_pass pg_db rustfs_key rustfs_secret
  pg_user="$(env_get POSTGRES_USER)";          pg_user="${pg_user:-inboxos}"
  pg_pass="$(env_get POSTGRES_PASSWORD)";      pg_pass="${pg_pass:-secretkey}"
  pg_db="$(env_get POSTGRES_DB)";              pg_db="${pg_db:-inboxos}"
  rustfs_key="$(env_get RUSTFS_ACCESS_KEY)";   rustfs_key="${rustfs_key:-inboxos}"
  rustfs_secret="$(env_get RUSTFS_SECRET_KEY)"; rustfs_secret="${rustfs_secret:-secretkey}"

  cat >"$ENV_DOCKER" <<EOF
# GENERATED by scripts/stack-up.sh — local-docker overrides for the full
# container stack. Regenerated on every run; edit .env, not this file.

# In-network service endpoints (replace the host/localhost values in .env)
DATABASE_URL=postgresql://${pg_user}:${pg_pass}@postgres:5432/${pg_db}?schema=public
REDIS_URL=redis://redis:6379
S3_ENDPOINT=http://filesystem:9000
S3_REGION=us-east-1
S3_BUCKET=chatbotx
S3_ACCESS_KEY_ID=${rustfs_key}
S3_SECRET_ACCESS_KEY=${rustfs_secret}
JAVASCRIPT_EXECUTOR_URL=http://javascript-executor:3210
ZALO_PERSONAL_GATEWAY_URL=http://zalo-personal-gateway:3220

# Local URLs — plain HTTP, no forced HTTPS
NEXT_PUBLIC_BUILDER_URL=http://localhost:${BUILDER_PORT}
# Broker origin is also the base for integration webhooks (e.g. the Zalo
# personal gateway POSTs history/live messages to <broker>/integrations/...).
# In the all-docker stack the gateway container reaches the builder through
# the host-published port, not through "localhost" (which is the gateway
# itself) — container-to-container calls to "builder:3000" would bypass the
# user's reverse-proxy path, so go via host.docker.internal instead.
NEXT_PUBLIC_BROKER_URL=http://host.docker.internal:${BUILDER_PORT}
BETTER_AUTH_URL=http://localhost:${BUILDER_PORT}
FORCE_PUBLIC_HTTPS=false
NEXT_PUBLIC_INTERNAL_STORAGE_URL=http://localhost:29000/inboxos/

# Mail goes to the in-stack MailHog (UI http://localhost:8025)
SMTP_SERVER=smtp://mailhog:1025
SMTP_FROM=InboxOS <no-reply@inboxos.local>
EOF
}

# ── lifecycle ───────────────────────────────────────────────────────────────

# Host dev processes (`pnpm dev` / `scripts/dev-up.sh`) hold :3123 and :1999
# that the docker stack needs. Stop them — scoped to this checkout so other
# projects' node processes survive.
stop_host_dev() {
  if [[ -f /tmp/inboxos-dev.pid ]]; then
    local pid pgid=""
    pid=$(cat /tmp/inboxos-dev.pid)
    if kill -0 "$pid" 2>/dev/null; then
      pgid=$(ps -o pgid= -p "$pid" 2>/dev/null | tr -d ' ' || true)
      [[ -n "$pgid" ]] && { log "stopping dev-up session (pgid $pgid)"; kill -TERM -- "-$pgid" 2>/dev/null || true; sleep 2; }
    fi
    rm -f /tmp/inboxos-dev.pid
  fi
  # Match the dev commands under this checkout's path, not a hardcoded repo
  # name — the folder may still be ChatbotX after the InboxOS rename. Only the
  # dev servers are matched so editor tooling (tsserver, Biome LSP) and test
  # runs from the same checkout survive.
  local root_re pat
  root_re=$(printf '%s' "$ROOT" | sed 's/[][\.*^$()+?{}|]/\\&/g')
  pat="${root_re}/.*(turbo.*dev|next dev|tsx --watch)"
  if pgrep -f "$pat" >/dev/null 2>&1; then
    log "stopping leftover host dev processes holding stack ports…"
    pkill -f "$pat" 2>/dev/null || true
    for _ in $(seq 1 10); do
      lsof -i :3123 -i :1999 2>/dev/null | grep -q LISTEN || break
      sleep 1
    done
  fi
  if lsof -i :3123 -i :1999 2>/dev/null | grep -q LISTEN; then
    log "ports still busy — offenders:"; lsof -i :3123 -i :1999 | grep LISTEN || true
    die "free :3123 and :1999 first"
  fi
}

down() {
  log "stopping full stack…"
  "${COMPOSE[@]}" --profile zalo-personal down "$@"
}

wait_for_builder() {
  log "waiting for builder on :$BUILDER_PORT (first image build can take several minutes)…"
  for _ in $(seq 1 300); do
    if curl -sf -m 3 "$HEALTH_URL" >/dev/null 2>&1; then
      log "builder healthy: http://localhost:$BUILDER_PORT"
      return 0
    fi
    # fail fast when a container died
    local dead
    dead=$("${COMPOSE[@]}" ps --format '{{.Name}} {{.State}}' 2>/dev/null \
      | awk '$2=="exited" || $2=="dead" {print $1}' \
      | grep -v 'filesystem-init' || true)
    if [[ -n "$dead" ]]; then
      die "container exited: $dead — check logs: ${COMPOSE[*]} logs $dead"
    fi
    sleep 3
  done
  die "builder never became healthy in 15min — ${COMPOSE[*]} logs builder"
}

case "${1:-}" in
  --down)
    down; exit 0 ;;
  --reset)
    down -v; rm -f "$ENV_DOCKER"; log "volumes + .env.docker wiped" ;;
esac

docker info >/dev/null 2>&1 || die "docker daemon not reachable"
stop_host_dev
ensure_base_env
write_docker_env

log "docker compose up (build$([[ "${1:-}" == "--build" ]] && echo ' --build'))…"
up_args=(-d --remove-orphans)
[[ "${1:-}" == "--build" ]] && up_args+=(--build)
"${COMPOSE[@]}" --profile zalo-personal up "${up_args[@]}"
# Bucket init runs to exit-0 (one-shot); start it explicitly since nothing
# depends_on it.
"${COMPOSE[@]}" up -d filesystem-init >/dev/null 2>&1 || true

wait_for_builder

cat <<EOF

  ┌─ full docker stack ready ───────────────────────────────┐
  │  builder    http://localhost:${BUILDER_PORT}  (demo@example.com / Demo@1234) │
  │  mailhog    http://localhost:8025                        │
  │  adminer    http://localhost:28080  (server: postgres)   │
  │  rustfs     http://localhost:29001  (S3 :29000)          │
  │  redisinsight http://localhost:5540                      │
  │  realtime   ws://localhost:1999                          │
  └──────────────────────────────────────────────────────────┘
  logs:  docker compose -f docker-compose.dev.yml -f docker-compose.override.yml logs -f
  down:  scripts/stack-up.sh --down
EOF

[[ "${1:-}" == "--logs" ]] && exec "${COMPOSE[@]}" logs -f
